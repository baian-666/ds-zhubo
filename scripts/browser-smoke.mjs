import assert from 'node:assert/strict'
import { mkdirSync } from 'node:fs'
import { once } from 'node:events'
import { createApp } from '../apps/cohost/server.mjs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({viewport:{width:1440,height:1050}})
await page.addInitScript(() => {
  localStorage.setItem('onboarding/completed','true')
  localStorage.setItem('onboarding/skipped','false')
})
const server=createApp({apiKey:'',token:''})
server.listen(0,'127.0.0.1'); await once(server,'listening')
const base='http://127.0.0.1:'+server.address().port
const errors=[]
page.on('pageerror', error => errors.push(error.message))
let requests=0
page.on('request', request=>{if(request.url().endsWith('/api/reply')) requests++})
const waitResult=async pattern=>page.waitForFunction(pattern=>new RegExp(pattern).test(document.getElementById('result').textContent), pattern)
try {
  await page.goto(base)
  await page.locator('#status').filter({hasText:'队列'}).waitFor()
  await page.locator('#engine').selectOption('mock')
  await page.locator('#hostSubmit').click()
  await page.waitForTimeout(600)
  assert.equal(requests,0,'manual speech must not invoke generation')
  await page.locator('.message.director .bubble').filter({hasText:'人工导演模式'}).waitFor()
  await page.locator('#manualReply').click()
  await waitResult('文字回答完成')
  assert.equal(requests,1)
  await page.locator('.message.assistant .messageState').filter({hasText:'回答完成'}).waitFor()
  assert.equal(await page.locator('.message.host').count(),1,'manual reply reuses submitted speech')
  assert.equal(await page.locator('.message.assistant .avatar').first().textContent(), await page.locator('.message.director .avatar').first().textContent())
  await page.locator('#mode').selectOption('auto')
  await page.waitForTimeout(500)
  await page.locator('#hostSubmit').click()
  await waitResult('文字回答完成')
  await page.waitForTimeout(500)
  assert.equal(requests,2,'automatic handover generates exactly once')
  await page.locator('#scenario').selectOption('pause')
  await page.locator('#hostSubmit').click()
  await page.waitForTimeout(600)
  assert.equal(requests,2,'pause must not generate')
  assert.ok((await page.locator('.message.director .bubble').allTextContents()).some(x=>x.includes('没有明确交棒证据')))
  await page.locator('#scenario').selectOption('handover')
  await page.locator('#hostSubmit').click()
  await page.waitForFunction(()=>document.querySelector('.message.assistant:last-child .bubble')?.textContent.length > 0)
  await page.locator('#scenario').selectOption('stop')
  await page.locator('#hostSubmit').click()
  await waitResult('打断')
  await page.waitForTimeout(400)
  assert.equal((await page.request.get(base+'/api/status').then(r=>r.json())).busy,false)
  assert.ok((await page.locator('.message.assistant .messageState').allTextContents()).some(x=>x.includes('已打断')))
  await page.locator('#viewerTab').click()
  await page.locator('#presetSend').click()
  await page.locator('.message.viewer').waitFor()
  await page.locator('#viewerWindow').check()
  await waitResult('文字回答完成')
  await page.waitForTimeout(500)
  const status=await page.request.get(base+'/api/status').then(r=>r.json())
  assert.equal(status.queued,0)
  await page.locator('#viewerText').fill('<img src=x onerror=alert(1)>')
  await page.locator('#enqueue').click()
  await page.locator('.message.viewer .bubble').filter({hasText:'<img src=x onerror=alert(1)>'}).waitFor()
  assert.equal(await page.locator('#messages img').count(),0,'chat treats input as plain text')
  await page.locator('#hostTab').click()
  await page.locator('#topicChange').click()
  await page.waitForFunction(()=>document.getElementById('feed').textContent.includes('暂无候选弹幕'))
  assert.equal(await page.locator('#viewerWindow').isChecked(),false)
  const count=await page.locator('.message').count()
  const other=await browser.newPage({viewport:{width:1440,height:1050}})
  await other.goto(base); await other.locator('.message.viewer').first().waitFor()
  assert.equal(await other.locator('.message').count(),count,'another tab sees the complete shared timeline')
  await other.close()
  await page.reload(); await page.locator('.message.viewer').first().waitFor()
  assert.equal(await page.locator('.message').count(),count,'refresh preserves room history')
  assert.equal(await page.locator('.message.assistant').count(),4)
  const ids=await page.locator('.message').evaluateAll(nodes=>nodes.map(x=>Number(x.dataset.id)))
  assert.deepEqual(ids,[...ids].sort((a,b)=>a-b),'streaming bubbles stay in server chronology')
  const layout=await page.evaluate(()=>{
    const rect=id=>document.getElementById(id).getBoundingClientRect()
    const stage=rect('stagePanel'),chat=document.querySelector('.chatPanel').getBoundingClientRect(),input=document.querySelector('.inputPanel').getBoundingClientRect()
    return {ordered:stage.right<=chat.left && chat.right<=input.left,captionClear:rect('answer').top>=rect('stage').bottom,hostRight:rect('hostText').left>=input.left}
  })
  assert.deepEqual(layout,{ordered:true,captionClear:true,hostRight:true})
  await page.locator('#expandStage').click()
  assert.equal(await page.locator('#expandStage').getAttribute('aria-expanded'),'true')
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('#expandStage').getAttribute('aria-expanded'),'false')
  mkdirSync('data',{recursive:true})
  await page.locator('#latest').click()
  await page.screenshot({path:'data/room-desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'data/room-mobile.png',fullPage:true})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  assert.deepEqual(errors,[])
  await page.locator('summary').filter({hasText:'本场配置与清空'}).click()
  await page.locator('#reset').click()
  await page.waitForFunction(()=>document.querySelectorAll('.message').length===1)
  assert.equal(await page.locator('.message.host').count(),0)
  console.log(JSON.stringify({passed:true,generationRequests:requests,chatEntries:count,pageErrors:errors,screenshots:['data/room-desktop.png','data/room-mobile.png']}))
} finally {await browser.close();server.closeAllConnections();await new Promise(resolve=>server.close(resolve))}
